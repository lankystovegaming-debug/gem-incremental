import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
const read = p => readFileSync(new URL(p, import.meta.url), 'utf8');
const manifest = JSON.parse(read('./manifest.v1.json'));
const registry = JSON.parse(read('./equipment.v1.json'));
const literal = value => `'${JSON.stringify(value).replaceAll("'", "''")}'::jsonb`;
const text = value => `'${value.replaceAll("'", "''")}'`;
const lines = [
  `insert into public.world2_manifests(version,definition) values(1,${literal({...manifest,equipmentCompatibility:{attachedEffects:registry.attachedEffects,attachedContract:registry.attachedContract,unknownPolicy:registry.unknownPolicy}})});`,
  ...manifest.laws.map(l => `insert into public.world2_law_definitions(version,category,law_id,weight,contract) values(1,${text(l.category)},${text(l.id)},${l.weight},${literal(l)});`),
  ...manifest.adaptation.levels.map(l => `insert into public.world2_adaptation_levels(version,level,factor,qualifying_rolls) values(1,${l.level},${l.factor},${l.qualifyingRolls});`),
  ...registry.entries.map(e => `insert into public.world2_equipment_registry(version,equipment_id,native_world,verification,contract) values(1,${text(e.id)},${e.nativeWorld},${text(e.verification)},${literal(e)});`),
  'insert into abyss_private.release_config(singleton,manifest_version) values(true,1);',
];
// A released version is immutable: future balancing creates v2, never edits v1.
const sql = '-- Generated by world2/build-migration.mjs. Review world2/schema.sql and versioned JSON.\n' +
  read('./schema.sql').replace('-- CONFIGURATION_SEED', lines.join('\n'));
const target = new URL('../supabase/migrations/20261029002115_world2_abyss_phase1_foundations.sql', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== sql) throw new Error('world2 migration is stale; run node world2/build-migration.mjs');
} else writeFileSync(target, sql);
console.log('World 2 migration SHA-256:', createHash('sha256').update(sql).digest('hex'));
