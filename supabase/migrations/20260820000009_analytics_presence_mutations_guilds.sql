create table if not exists public.player_presence (
  player_id uuid primary key references public.players(id) on delete cascade,
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  total_sessions bigint not null default 0
);

create table if not exists public.player_presence_events (
  id bigint generated by default as identity primary key,
  player_id uuid not null references public.players(id) on delete cascade,
  seen_at timestamptz not null default now()
);

create index if not exists player_presence_last_seen_idx
  on public.player_presence(last_seen_at desc);
create index if not exists player_presence_events_seen_at_idx
  on public.player_presence_events(seen_at desc);
create index if not exists player_presence_events_player_seen_idx
  on public.player_presence_events(player_id, seen_at desc);

alter table public.player_presence enable row level security;
alter table public.player_presence_events enable row level security;
revoke all on public.player_presence, public.player_presence_events from anon, authenticated;
grant select, insert, update on public.player_presence, public.player_presence_events to service_role;
grant usage, select on sequence public.player_presence_events_id_seq to service_role;

create or replace function public.record_player_presence()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_now timestamptz := now();
  v_first timestamptz;
begin
  if v_uid is null then
    raise exception 'not_authenticated';
  end if;

  insert into public.player_presence(player_id, first_seen_at, last_seen_at, total_sessions)
  values(v_uid, v_now, v_now, 1)
  on conflict(player_id) do update
    set last_seen_at = excluded.last_seen_at;

  select first_seen_at into v_first
  from public.player_presence
  where player_id = v_uid;

  insert into public.player_presence_events(player_id, seen_at)
  values(v_uid, v_now);

  -- Keep the heartbeat table bounded without running a large delete on every
  -- one-minute heartbeat. The modulo check simply spreads cleanup across
  -- ordinary player traffic.
  if mod(extract(epoch from v_now)::bigint, 97) = 0 then
    delete from public.player_presence_events
    where seen_at < v_now - interval '45 days';
  end if;

  return jsonb_build_object(
    'ok', true,
    'firstSeenAt', v_first,
    'lastSeenAt', v_now
  );
end;
$$;

revoke all on function public.record_player_presence() from public;
grant execute on function public.record_player_presence() to authenticated;

