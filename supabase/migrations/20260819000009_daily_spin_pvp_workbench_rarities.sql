create or replace function public.claim_daily_spin()
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := auth.uid();
  v_cfg public.daily_spin_config%rowtype;
  v_item jsonb;
  v_reward jsonb;
  v_total numeric := 0;
  v_roll numeric;
  v_cursor numeric := 0;
  v_date date := current_date;
  v_money numeric;
  v_coins numeric;
  v_qty integer;
  v_reward_type text;
  v_consumable text;
  v_gem_name text;
  v_gem jsonb;
begin
  if v_uid is null then raise exception 'not_authenticated'; end if;

  select * into v_cfg from public.daily_spin_config where id = true for update;
  if not found or not v_cfg.enabled then raise exception 'feature_disabled'; end if;

  if exists (
    select 1 from public.daily_spin_claims
    where player_id = v_uid and claim_date = v_date
  ) then
    raise exception 'already_claimed';
  end if;

  if jsonb_typeof(v_cfg.rewards) <> 'array' or jsonb_array_length(v_cfg.rewards) = 0 then
    raise exception 'no_rewards_configured';
  end if;

  select coalesce(sum(greatest(0, coalesce((x->>'chance')::numeric,0))),0)
    into v_total
  from jsonb_array_elements(v_cfg.rewards) x;

  if v_total <= 0 then raise exception 'invalid_rewards'; end if;

  v_roll := random() * v_total;

  for v_item in select value from jsonb_array_elements(v_cfg.rewards)
  loop
    v_cursor := v_cursor + greatest(0, coalesce((v_item->>'chance')::numeric,0));
    if v_roll <= v_cursor then
      v_reward := coalesce(v_item->'reward', '{}'::jsonb) || jsonb_build_object(
        'id', coalesce(v_item->>'id',''),
        'label', coalesce(v_item->>'label','Reward')
      );
      exit;
    end if;
  end loop;

  if v_reward is null then
    v_reward := coalesce(v_cfg.rewards->-1->'reward','{}'::jsonb);
  end if;

  v_reward_type := v_reward->>'type';

  if v_reward_type = 'money' then
    v_money := greatest(0, coalesce((v_reward->>'amount')::numeric,0));
    update public.players
      set money = greatest(0, coalesce(money,0) + v_money),
          lifetime_earnings = greatest(0, coalesce(lifetime_earnings,0) + v_money)
      where id = v_uid;
  elsif v_reward_type = 'coins' then
    v_coins := greatest(0, coalesce((v_reward->>'amount')::numeric,0));
    update public.players
      set coins = greatest(0, coalesce(coins,0) + v_coins)
      where id = v_uid;
  elsif v_reward_type = 'potion' then
    v_consumable := v_reward->>'consumableId';
    v_qty := greatest(1, coalesce((v_reward->>'amount')::integer,1));
    if not exists(select 1 from public.game_consumables where id=v_consumable) then
      raise exception 'invalid_consumable';
    end if;
    insert into public.player_consumables(player_id,consumable_id,quantity,updated_at)
    values(v_uid,v_consumable,v_qty,now())
    on conflict(player_id,consumable_id) do update
      set quantity = public.player_consumables.quantity + excluded.quantity,
          updated_at = now();
  elsif v_reward_type = 'capacity' then
    update public.players
      set inventory_capacity = greatest(0, coalesce(inventory_capacity,0) + greatest(0,coalesce((v_reward->>'amount')::integer,0)))
      where id=v_uid;
  elsif v_reward_type = 'boost' then
    if (v_reward->>'family') not in ('luck','rollSpeed','weightLuck','weightMultiplier') then
      raise exception 'invalid_boost_family';
    end if;
    insert into public.player_boosts(player_id,family,tier,effect_value,expires_at,updated_at)
    values(
      v_uid,
      v_reward->>'family',
      3,
      greatest(0.0001,coalesce((v_reward->>'effectValue')::numeric,0)),
      now()+make_interval(secs=>greatest(1,coalesce((v_reward->>'seconds')::integer,300))),
      now()
    )
    on conflict(player_id,family) do update
      set tier=excluded.tier,effect_value=excluded.effect_value,expires_at=excluded.expires_at,updated_at=now();
  elsif v_reward_type = 'gem' then
    v_gem_name := v_reward->>'gemName';
    select to_jsonb(g) into v_gem
    from public.private_feature_gems g
    where g.name=v_gem_name and g.enabled=true
    order by g.rarity asc
    limit 1;
    if v_gem is null then raise exception 'invalid_gem_reward'; end if;
    insert into public.inventory_gems(
      player_id,gem_name,rarity,base_weight,value_per_gram,
      rolled_weight_multiplier,rolled_weight,final_weight,
      mutation_id,mutation_multiplier,mutation_ids,mutation_multipliers,
      value,locked,roll_number,luck_at_roll
    )
    values(
      v_uid,v_gem->>'name',(v_gem->>'rarity')::numeric,(v_gem->>'base_weight')::numeric,(v_gem->>'value_per_gram')::numeric,
      1,(v_gem->>'base_weight')::numeric,(v_gem->>'base_weight')::numeric,
      null,1,'{}'::text[],'{}'::jsonb,
      (v_gem->>'base_weight')::numeric*(v_gem->>'value_per_gram')::numeric,
      false,(select coalesce(total_rolls,0) from public.players where id=v_uid),1
    );
  end if;

  insert into public.daily_spin_claims(player_id,claim_date,reward)
  values(v_uid,v_date,v_reward);

  return jsonb_build_object('success',true,'claimDate',v_date,'reward',v_reward);
exception
  when unique_violation then
    raise exception 'already_claimed';
end;
$$;

grant execute on function public.claim_daily_spin() to authenticated;

