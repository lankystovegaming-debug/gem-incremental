  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.pvp_matches (
  id uuid primary key default gen_random_uuid(),
  challenger_id uuid not null references public.players(id) on delete cascade,
  opponent_id uuid not null references public.players(id) on delete cascade,
  challenger_weapon_id uuid references public.pvp_weapon_definitions(id),
  opponent_weapon_id uuid references public.pvp_weapon_definitions(id),
  challenger_hp numeric not null default 100,
  opponent_hp numeric not null default 100,
  turn_player_id uuid not null references public.players(id) on delete cascade,
  status text not null default 'active' check(status in ('active','won','lost','draw','abandoned')),
  battle_log jsonb not null default '[]'::jsonb,
  winner_id uuid references public.players(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

