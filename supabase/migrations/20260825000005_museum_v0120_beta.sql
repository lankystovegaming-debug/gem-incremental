alter table public.inventory_gems
  add column if not exists museum_locked boolean not null default false;

create table if not exists public.museum_profiles (
  player_id uuid primary key references public.players(id) on delete cascade,
  museum_name text not null default 'My Gem Museum',
  capacity integer not null default 4 check (capacity between 4 and 10),
  prestige numeric not null default 0,
  tier integer not null default 1,
  collections_completed integer not null default 0,
  highest_exhibit_score numeric not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.museum_exhibits (
  player_id uuid not null references public.players(id) on delete cascade,
  slot integer not null check (slot between 1 and 10),
  specimen_id bigint not null unique references public.inventory_gems(id) on delete restrict,
  prestige numeric not null default 0,
  snapshot jsonb not null default '{}'::jsonb,
  added_at timestamptz not null default now(),
  primary key (player_id, slot)
);

create table if not exists public.museum_registrations (
  id bigint generated by default as identity primary key,
  player_id uuid not null references public.players(id) on delete cascade,
  original_specimen_id bigint not null,
  specimen_snapshot jsonb not null,
  registered_at timestamptz not null default now(),
  unique (player_id, original_specimen_id)
);

create table if not exists public.museum_collection_definitions (
  id text primary key,
  name text not null,
  description text not null,
  kind text not null check (kind in ('permanent', 'showcase')),
  prestige_reward integer not null check (prestige_reward >= 0),
  requirements jsonb not null,
  cosmetic_reward text,
  sort_order integer not null default 0,
  enabled boolean not null default true
);

create table if not exists public.museum_collection_completions (
  player_id uuid not null references public.players(id) on delete cascade,
  collection_id text not null references public.museum_collection_definitions(id) on delete cascade,
  completed_at timestamptz not null default now(),
  primary key (player_id, collection_id)
);

create table if not exists public.museum_purchases (
  id bigint generated by default as identity primary key,
  player_id uuid not null references public.players(id) on delete cascade,
  purchase_kind text not null,
  money_removed numeric not null check (money_removed >= 0),
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

