async function seed(uid,name) {
  await db.query('insert into players values($1,$2,3000000000,1000000,5000000000,\'{}\')',[uid,name]);
  await db.query("insert into player_consumables values($1,'legendary-potion',50,now()),($1,'mythic-potion',25,now())",[uid]);
  await db.exec(`insert into private_feature_gems(name,base_weight,special_gem) values('History Gem',100,false) on conflict do nothing;
    insert into game_mutations select 'ordinary-'||n,true from generate_series(1,50)n on conflict do nothing;`);
  await db.query("insert into player_gem_mutation_combinations values($1,'History Gem',array(select 'ordinary-'||n from generate_series(1,50)n))",[uid]);
  for(let n=1;n<=10;n++) {
    const gem=`Special ${n}`;
    await db.query('insert into private_feature_gems values($1,100,true,true) on conflict do nothing',[gem]);
    await db.query("insert into player_gem_mutation_combinations values($1,$2,'{}')",[uid,gem]);
  }
  const specialists=['tectonic-pickaxe','the-accelerator','the-resonator','the-excavator','fortune-pickaxe','supersizer-pickaxe'];
  for(const id of specialists) await db.query('insert into equipment_ownership_history values($1,$2)',[uid,id]);
  for(let n=1;n<=10;n++) await db.query('insert into best_roll_history(player_id,gem_name,rarity,final_weight,roll_number) values($1,\'History Gem\',$2,$3,$4)',[uid,n===1?500000000:100000000,n===1?2500:1000,n]);
  await db.query("insert into inventory_gems(player_id,gem_name,rarity,base_weight,final_weight,value) values($1,'Manual Cosmic',10000000,200000,5000000,100000000)",[uid]);
}

