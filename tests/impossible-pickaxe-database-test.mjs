async function seed(uid,name) {
  await db.query('insert into players values($1,$2,3000000000,1000000,5000000000,\'{}\')',[uid,name]);
  await db.query("insert into player_consumables values($1,'legendary-potion',50,now()),($1,'mythic-potion',25,now())",[uid]);
  await db.exec(`insert into private_feature_gems(name,base_weight,special_gem) values('History Gem',100,false) on conflict do nothing;
    insert into game_mutations select 'ordinary-'||n,true from generate_series(1,50)n on conflict do nothing;`);
  await db.query("insert into player_gem_mutation_combinations values($1,'History Gem',array(select 'ordinary-'||n from generate_series(1,50)n))",[uid]);
  for(let n=1;n<=10;n++) {
    const gem=`Special ${n}`;
    await db.query('insert into private_feature_gems values($1,100,true,true) on conflict do nothing',[gem]);
    await db.query("insert into player_gem_mutation_combinations values($1,$2,'{}')",[uid,gem]);
  }
  const specialists=['tectonic-pickaxe','the-accelerator','the-resonator','the-excavator','fortune-pickaxe','supersizer-pickaxe'];
  for(const id of specialists) await db.query('insert into equipment_ownership_history values($1,$2)',[uid,id]);
  for(let n=1;n<=10;n++) await db.query('insert into best_roll_history(player_id,gem_name,rarity,final_weight,roll_number) values($1,\'History Gem\',$2,$3,$4)',[uid,n===1?500000000:100000000,n===1?2500:1000,n]);
  await db.query(`insert into inventory_gems(player_id,gem_name,rarity,base_weight,final_weight,value)
    select $1::uuid,'Common',1,1000000,1000000,11000 from generate_series(1,1000)
    union all select $1,'Legendary',1000,100,100,11000 from generate_series(1,67000)
    union all select $1,'Mythic',10000,100,100,11000 from generate_series(1,30000)
    union all select $1,'Exotic',100000,100,100,11000 from generate_series(1,500)
    union all select $1,'Exalted',1000000,100,100,11000 from generate_series(1,30)
    union all select $1,'Cosmic',10000000,
      case when n=1 then 200000 when n<=4 then 333333.333333 when n<=14 then 500000 else 5000000 end,
      5000000,case when n=1 then 100000000 else 11000 end from generate_series(1,15)n`,[uid]);
}

await seed(first,'First Crafter'); await seed(later,'Later Crafter');
async function asUser(uid) { await db.query("select set_config('request.jwt.claim.sub',$1,false)",[uid]); await db.exec('set role authenticated'); }
async function reset(){await db.exec('reset role');}

await asUser(first);
const firstPlan=await value('select prepare_impossible_pickaxe_craft() result');
assert.equal(firstPlan.ready,true);
assert.equal(Number(firstPlan.preview.materials.selectedCount),98545,'shared predicates do not consume a specimen twice');
assert.equal(Number(firstPlan.preview.materials.multiplier10),14,'10 + 3 + 1 multiplier slots use distinct specimens');
assert.equal(Number(firstPlan.preview.materials.multiplier15),4);
assert.equal(Number(firstPlan.preview.materials.multiplier25),1);
const firstCraft=await value('select craft_impossible_pickaxe($1) result',[firstPlan.token]);
assert.equal(firstCraft.worldFirst,true);
await reset();
assert.equal(await value('select count(*)::int result from impossible_pickaxe_world_first'),1);
assert.equal(await value("select exists(select 1 from player_cosmetics where player_id=$1 and cosmetic_id='impossible-profile-background') result",[first]),true);

await asUser(later);
let laterPlan=await value('select prepare_impossible_pickaxe_craft() result');
assert.equal(laterPlan.ready,true);
await reset();
const selected=await value('select specimen_ids[1] result from impossible_pickaxe_craft_plans where token=$1',[laterPlan.token]);
await db.query('update inventory_gems set locked=true where id=$1',[selected]);
const before=await db.query("select money,(select quantity from player_consumables where player_id=$1 and consumable_id='legendary-potion') legendary,(select count(*) from inventory_gems where player_id=$1) gems from players where id=$1",[later]);
await asUser(later);
await assert.rejects(()=>db.query('select craft_impossible_pickaxe($1)',[laterPlan.token]),/craft_plan_changed/);
await reset();
const after=await db.query("select money,(select quantity from player_consumables where player_id=$1 and consumable_id='legendary-potion') legendary,(select count(*) from inventory_gems where player_id=$1) gems from players where id=$1",[later]);
assert.deepEqual(after.rows,before.rows,'changed plans roll back every destructive write');
await db.query('update inventory_gems set locked=false where id=$1',[selected]);
await asUser(later);
laterPlan=await value('select prepare_impossible_pickaxe_craft() result');
const laterCraft=await value('select craft_impossible_pickaxe($1) result',[laterPlan.token]);
assert.equal(laterCraft.worldFirst,false);
await reset();
assert.equal(await value("select exists(select 1 from player_cosmetics where player_id=$1 and cosmetic_id='impossible-profile-background') result",[later]),false);
assert.equal(await value("select exists(select 1 from player_cosmetics where player_id=$1 and cosmetic_id='impossible-pickaxe-crafter') result",[later]),true);
assert.equal(await value('select count(*)::int result from impossible_pickaxe_world_first'),1);
await db.close();
console.log('Impossible Pickaxe database plan, atomic rollback, singleton winner, entitlement gating and later-crafter behavior passed.');
