import assert from 'node:assert/strict';
import {luckLayers} from '../supabase/functions/roll/equipmentRules.js';
const input={pickaxe:26,clover:1.1,enchant:1.35,guild:1.1,research:1.05,focused:1.03,flat:1,special:3,oneRoll:10000,world:2};
const result=luckLayers(input);
assert.ok(Math.abs(result.personal-1.53)<1e-9);
assert.ok(Math.abs(result.final-20268.548)<1e-9);
const ordinary=luckLayers({...input,oneRoll:0});
assert.equal(result.final-ordinary.final,20000,'world doubles one-roll Luck; specials never do');
const special=luckLayers({...input,special:6});
assert.ok(Math.abs(special.final-result.final-ordinary.final)<1e-9,'doubling specials affects only ordinary Luck');
const ascension=luckLayers({...input,enchant:51.35});
assert.ok(Math.abs(ascension.final-result.final-26*1.1*50*3*2)<1e-8,'Ascension is +50 to the enchant component');
console.log('Locked additive Luck layers and special/one-roll/world placement passed.');
