import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const source=readFileSync(new URL('../supabase/functions/roll/index.ts',import.meta.url),'utf8').split('// QOL_RULES_START')[1].split('// QOL_RULES_END')[0];
const {gemFilterDecision:decide}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const gem={gem_name:'Quartz',rarity:10,effectiveRarity:10},seen=new Set(['Quartz']);
const settings={autoKeep:false,discoveryKeep:false,gemFilter:{Quartz:'SELL'}};
assert.equal(decide(settings,gem,seen).sell,true);
assert.equal(decide({...settings,gemFilter:{Quartz:'KEEP'}},gem,seen).keep,true);
assert.equal(decide({...settings,gemFilter:{Quartz:'DEFAULT'}},gem,seen).sell,false);
assert.equal(decide({...settings,autoKeep:true,autoKeepEffectiveRarity:1000},{...gem,effectiveRarity:1000},seen).reason,'auto-keep');
assert.equal(decide({...settings,autoKeep:true,autoKeepEffectiveRarity:1000},{...gem,effectiveRarity:999},seen).sell,true);
for(const threshold of [9,10])assert.equal(decide({...settings,discoveryKeep:true,discoveryKeepRarity:threshold},gem,new Set()).reason,'discovery');
assert.equal(decide({...settings,discoveryKeep:true,discoveryKeepRarity:11},{...gem,effectiveRarity:1e10},new Set()).sell,true,'discovery uses RAW rarity');
assert.equal(decide({...settings,discoveryKeep:true,discoveryKeepRarity:10},gem,seen).sell,true,'later copies follow SELL');
assert.equal(decide(settings,{...gem,gem_name:'Ancient Relic'},seen).keep,true);
const legacy={autoKeep:false,discoveryKeep:false,legacyAutoSell:true,legacyAutoSellTier:'epic'};
assert.equal(decide(legacy,{...gem,rarity:1000},seen).sell,true);
assert.equal(decide(legacy,{...gem,rarity:1001},seen).sell,false);
assert.equal(decide({...legacy,gemFilter:{Quartz:'DEFAULT'}},gem,seen).sell,false,'explicit DEFAULT clears inherited SELL');
assert.equal(decide({...legacy,gemFilter:{Quartz:'KEEP'}},gem,seen).keep,true);
assert.equal(decide({autoKeep:false,gemFilter:{Quartz:'SELL'}},{...gem,rarity:10000},new Set()).keep,true,'new-player discovery default is 10000');
console.log('QoL rule matrix: KEEP/SELL/DEFAULT, threshold boundaries, first discovery, raw/effective rarity, relics and legacy fallback passed.');
