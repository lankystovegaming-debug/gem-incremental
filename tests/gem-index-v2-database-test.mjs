import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { PGlite } from "@electric-sql/pglite";

const migration = readFileSync(
  new URL("../supabase/migrations/20260923142634_repair_gem_index_v2.sql", import.meta.url),
  "utf8"
);
const db = new PGlite();

await db.exec(`
  create role anon;
  create role authenticated;
  create role service_role;
  create schema auth;
  create function auth.uid() returns uuid language sql stable as $$ select null::uuid $$;
  create function auth.role() returns text language sql stable as $$ select 'service_role'::text $$;
  create table public.players (id uuid primary key);
  create table public.code_improvement (user_id uuid);
  create table public.player_gem_mutation_combinations (
    id bigint generated by default as identity primary key,
    player_id uuid not null references public.players(id) on delete cascade,
    gem_name text not null,
    combination_key text not null,
    mutation_ids text[] not null default '{}',
    mutation_multipliers jsonb not null default '{}',
    total_found bigint not null default 0,
    highest_value numeric not null default 0,
    first_discovered_at timestamptz not null default now(),
    last_discovered_at timestamptz not null default now(),
    unique (player_id, gem_name, combination_key)
  );
  create table public.private_feature_gems (
    id uuid primary key,
    title text,
    name text not null,
    rarity double precision not null,
    base_weight numeric not null,
    value_per_gram numeric not null,
    description text,
    metadata jsonb,
    hide_rarity_until_discovered boolean,
    affected_by_luck boolean,
    enabled boolean,
    sort_order integer,
    starts_at timestamptz,
    ends_at timestamptz,
    updated_at timestamptz,
    availability_mode text,
    daily_start_time time,
    daily_end_time time,
    daily_time_windows jsonb,
    availability_timezone text,
    required_event_key text,
    special_gem boolean
  );
  insert into public.players values ('00000000-0000-0000-0000-000000000001');
  insert into public.player_gem_mutation_combinations
    (player_id, gem_name, combination_key, mutation_ids, mutation_multipliers,
     total_found, highest_value, first_discovered_at, last_discovered_at)
  values
    ('00000000-0000-0000-0000-000000000001', 'Ruby', 'polished+gilded',
     array['Polished','gilded'], '{"polished":1.5}', 2, 10, '2026-01-02', '2026-01-03'),
    ('00000000-0000-0000-0000-000000000001', 'Ruby', 'gilded+polished',
     array['gilded','polished'], '{"gilded":2.5}', 3, 12, '2026-01-01', '2026-01-04');
  insert into public.private_feature_gems
    (id, title, name, rarity, base_weight, value_per_gram, description, metadata,
     hide_rarity_until_discovered, affected_by_luck, enabled, sort_order,
     starts_at, ends_at, updated_at, availability_mode, availability_timezone, special_gem)
  values
    ('00000000-0000-0000-0000-000000000010', '', 'Historical', 100, 1, 1, '', '{}', false, true, true, 1,
     '2025-01-01', '2025-02-01', now(), 'date_range', 'Asia/Singapore', false),
    ('00000000-0000-0000-0000-000000000011', '', 'Disabled', 10, 1, 1, '', '{}', false, true, false, 2,
     null, null, now(), 'always', 'Asia/Singapore', false);
`);

await db.exec(migration);

const repaired = await db.query(`
  select combination_key, mutation_ids, mutation_multipliers, total_found,
         highest_value, first_discovered_at::date::text as first_date,
         last_discovered_at::date::text as last_date
  from public.player_gem_mutation_combinations
  where gem_name = 'Ruby'
`);
assert.equal(repaired.rows.length, 1);
assert.deepEqual(repaired.rows[0], {
  combination_key: "gilded+polished",
  mutation_ids: ["gilded", "polished"],
  mutation_multipliers: { polished: 1.5, gilded: 2.5 },
  total_found: 5,
  highest_value: "12",
  first_date: "2026-01-01",
  last_date: "2026-01-04"
});

await db.query(`select public.record_gem_mutation_combination(
  '00000000-0000-0000-0000-000000000001', 'Ruby', 'wrong-order',
  array['POLISHED','gilded'], '{"gilded":2.5}', 15
)`);
const updated = await db.query(`select combination_key, total_found, highest_value
  from public.player_gem_mutation_combinations where gem_name = 'Ruby'`);
assert.deepEqual(updated.rows[0], {
  combination_key: "gilded+polished",
  total_found: 6,
  highest_value: "15"
});

const catalog = await db.query("select name from public.get_public_gem_index_catalog()");
assert.deepEqual(catalog.rows, [{ name: "Historical" }],
  "enabled expired gems remain visible, while disabled gems do not");

await db.close();
console.log("Gem Index v2 database checks passed.");
